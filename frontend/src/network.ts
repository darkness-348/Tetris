import type { LeaderboardEntry } from './types.ts';

const host = (typeof window !== 'undefined' && window.location.hostname) ? window.location.hostname : '127.0.0.1';
const protocol = (typeof window !== 'undefined' && window.location.protocol === 'https:') ? 'https:' : 'http:';
const wsProtocol = (typeof window !== 'undefined' && window.location.protocol === 'https:') ? 'wss:' : 'ws:';
const API_BASE = `${protocol}//${host}:8000`;
const WS_BASE = `${wsProtocol}//${host}:8000/ws`;

export interface NetworkCallbacks {
  onConnected?: (clientId: string) => void;
  onRoomCreated?: (roomId: string, seed: number, players: string[]) => void;
  onRoomJoined?: (roomId: string, seed: number, players: string[]) => void;
  onOpponentJoined?: (opponentName: string, players: string[]) => void;
  onMatchFound?: (roomId: string, seed: number, opponentName: string) => void;
  onCountdown?: (count: number) => void;
  onGameStart?: (seed: number) => void;
  onOpponentBoard?: (data: {
    matrix: number[][];
    score: number;
    lines: number;
    level: number;
    currentPiece?: any;
    holdPiece?: any;
  }) => void;
  onIncomingGarbage?: (lines: number, hole: number, attacker: string) => void;
  onGarbageSent?: (lines: number) => void;
  onOpponentReaction?: (emoji: string, sender: string) => void;
  onMatchEnded?: (winner: boolean, reason: string, winnerName: string) => void;
  onOpponentLeft?: (message: string) => void;
  onOpponentReady?: (ready: boolean) => void;
  onRematchOffered?: (sender: string) => void;
  onError?: (message: string) => void;
  onQueueWaiting?: (message: string) => void;
}

export class NetworkManager {
  private ws: WebSocket | null = null;
  private callbacks: NetworkCallbacks;
  public clientId: string = '';
  public isConnected: boolean = false;
  private reconnectTimer: number | null = null;

  constructor(callbacks: NetworkCallbacks = {}) {
    this.callbacks = callbacks;
  }

  // REST API Methods
  public async getHealth(): Promise<{ status: string; active_rooms: number; queue_count: number } | null> {
    try {
      const res = await fetch(`${API_BASE}/api/health`);
      if (!res.ok) return null;
      return await res.json();
    } catch {
      return null;
    }
  }

  public async getLeaderboard(mode: string = 'solo', limit: number = 20): Promise<LeaderboardEntry[]> {
    try {
      const res = await fetch(`${API_BASE}/api/leaderboard?mode=${mode}&limit=${limit}`);
      if (!res.ok) return [];
      const data = await res.json();
      return data.scores || [];
    } catch (err) {
      console.warn('Failed to fetch leaderboard:', err);
      return [];
    }
  }

  public async submitScore(
    playerName: string,
    score: number,
    lines: number,
    level: number,
    mode: string = 'solo'
  ): Promise<LeaderboardEntry | null> {
    try {
      const res = await fetch(`${API_BASE}/api/leaderboard`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          player_name: playerName,
          score,
          lines,
          level,
          mode,
        }),
      });
      if (!res.ok) return null;
      return await res.json();
    } catch (err) {
      console.warn('Failed to submit score:', err);
      return null;
    }
  }

  // 1. Fetch random pieces generated by the backend (generates constant HTTP traffic)
  public async fetchNextPieces(count: number = 1, level: number = 1): Promise<string[]> {
    try {
      const res = await fetch(`${API_BASE}/api/game/next-piece`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          count,
          level,
          player_id: this.clientId || 'player-solo',
        }),
      });
      if (!res.ok) return [];
      const data = await res.json();
      return (data.pieces || []).map((p: any) => p.piece_type);
    } catch (err) {
      console.warn('Backend piece fetch error (fallback to local generation):', err);
      return [];
    }
  }

  // 2. Automatically record loss when game over occurs
  public async recordAutoLoss(
    playerName: string,
    score: number,
    lines: number,
    level: number,
    durationSeconds: number,
    outcome: string = 'topped_out',
    mode: string = 'solo'
  ): Promise<any> {
    try {
      const res = await fetch(`${API_BASE}/api/game/record-loss`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          player_name: playerName,
          score,
          lines,
          level,
          duration_seconds: durationSeconds,
          outcome,
          mode,
        }),
      });
      if (!res.ok) return null;
      return await res.json();
    } catch (err) {
      console.warn('Auto loss recording error:', err);
      return null;
    }
  }

  // 3. Query real-time server traffic metrics
  public async getTrafficStats(): Promise<any> {
    try {
      const res = await fetch(`${API_BASE}/api/traffic`);
      if (!res.ok) return null;
      return await res.json();
    } catch {
      return null;
    }
  }

  // WebSocket Methods
  public connect() {
    if (this.ws && (this.ws.readyState === WebSocket.OPEN || this.ws.readyState === WebSocket.CONNECTING)) {
      return;
    }

    try {
      this.ws = new WebSocket(WS_BASE);

      this.ws.onopen = () => {
        this.isConnected = true;
        if (this.reconnectTimer) {
          clearTimeout(this.reconnectTimer);
          this.reconnectTimer = null;
        }
      };

      this.ws.onmessage = (event) => {
        try {
          const data = JSON.parse(event.data);
          this.handleMessage(data);
        } catch (e) {
          console.error('Error parsing WS message:', e);
        }
      };

      this.ws.onclose = () => {
        this.isConnected = false;
        // Try reconnecting in 3 seconds
        if (!this.reconnectTimer) {
          this.reconnectTimer = window.setTimeout(() => this.connect(), 3000);
        }
      };

      this.ws.onerror = (err) => {
        console.warn('WebSocket connection error:', err);
      };
    } catch (e) {
      console.warn('Cannot establish WebSocket:', e);
    }
  }

  private handleMessage(data: any) {
    switch (data.type) {
      case 'connected':
        this.clientId = data.clientId;
        this.callbacks.onConnected?.(data.clientId);
        break;
      case 'room_created':
        this.callbacks.onRoomCreated?.(data.roomId, data.seed, data.players);
        break;
      case 'room_joined':
        this.callbacks.onRoomJoined?.(data.roomId, data.seed, data.players);
        break;
      case 'opponent_joined':
        this.callbacks.onOpponentJoined?.(data.opponentName, data.players);
        break;
      case 'queue_waiting':
        this.callbacks.onQueueWaiting?.(data.message);
        break;
      case 'match_found':
        this.callbacks.onMatchFound?.(data.roomId, data.seed, data.opponentName);
        break;
      case 'opponent_ready':
        this.callbacks.onOpponentReady?.(data.ready);
        break;
      case 'countdown':
        this.callbacks.onCountdown?.(data.count);
        break;
      case 'game_start':
        this.callbacks.onGameStart?.(data.seed);
        break;
      case 'opponent_board':
        this.callbacks.onOpponentBoard?.(data);
        break;
      case 'incoming_garbage':
        this.callbacks.onIncomingGarbage?.(data.lines, data.hole, data.attacker);
        break;
      case 'garbage_sent':
        this.callbacks.onGarbageSent?.(data.lines);
        break;
      case 'opponent_reaction':
        this.callbacks.onOpponentReaction?.(data.emoji, data.sender);
        break;
      case 'match_ended':
        this.callbacks.onMatchEnded?.(data.winner, data.reason, data.winnerName);
        break;
      case 'opponent_left':
        this.callbacks.onOpponentLeft?.(data.message);
        break;
      case 'rematch_offered':
        this.callbacks.onRematchOffered?.(data.sender);
        break;
      case 'error':
        this.callbacks.onError?.(data.message);
        break;
    }
  }

  public send(data: any) {
    if (this.ws && this.ws.readyState === WebSocket.OPEN) {
      this.ws.send(JSON.stringify(data));
    }
  }

  public createRoom(playerName: string) {
    this.send({ type: 'create_room', playerName });
  }

  public joinRoom(roomId: string, playerName: string) {
    this.send({ type: 'join_room', roomId, playerName });
  }

  public joinQueue(playerName: string) {
    this.send({ type: 'join_queue', playerName });
  }

  public sendReady() {
    this.send({ type: 'player_ready' });
  }

  public sendBoardUpdate(
    matrix: number[][],
    score: number,
    lines: number,
    level: number,
    currentPiece?: any,
    holdPiece?: any
  ) {
    this.send({
      type: 'board_update',
      matrix,
      score,
      lines,
      level,
      currentPiece,
      holdPiece,
    });
  }

  public sendLinesCleared(count: number) {
    this.send({ type: 'lines_cleared', count });
  }

  public sendGameOver() {
    this.send({ type: 'game_over' });
  }

  public sendReaction(emoji: string) {
    this.send({ type: 'reaction', emoji });
  }

  public sendRematchRequest() {
    this.send({ type: 'rematch_request' });
  }
}
